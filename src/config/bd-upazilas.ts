export function getUpazilasByDistrict(districtId: string): string[] {
  if (!districtId) return [];
  const rawKey = districtId.toLowerCase().trim();
  const cleanKey = rawKey.replace(/[^a-z0-9]/g, "");

  const aliasKey = DISTRICT_KEY_ALIASES[rawKey] || DISTRICT_KEY_ALIASES[cleanKey];

  if (aliasKey && BD_UPAZILAS[aliasKey]) {
    return BD_UPAZILAS[aliasKey];
  }
  if (BD_UPAZILAS[rawKey]) {
    return BD_UPAZILAS[rawKey];
  }
  if (BD_UPAZILAS[cleanKey]) {
    return BD_UPAZILAS[cleanKey];
  }

  // Fallback to STEADFAST_LOCATIONS upazila dataset
  const foundInSteadfast = STEADFAST_LOCATIONS.find(
    (d) =>
      d.id === cleanKey ||
      d.id === rawKey ||
      d.name.toLowerCase() === cleanKey ||
      d.bnName === districtId.trim(),
  );

  if (foundInSteadfast && foundInSteadfast.upazilas && foundInSteadfast.upazilas.length > 0) {
    return foundInSteadfast.upazilas;
  }

  return ["সদর থানা / উপজেলা"];
}
